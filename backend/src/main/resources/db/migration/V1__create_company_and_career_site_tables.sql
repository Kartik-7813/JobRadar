
-- V1: Create Company and Career Site tables

CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(200) NOT NULL,

    normalized_name VARCHAR(200) NOT NULL,

    website_url VARCHAR(2048),

    canonical_domain VARCHAR(255),

    description TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_company_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- Company indexes

CREATE INDEX idx_companies_name
    ON companies (name);

CREATE INDEX idx_companies_normalized_name
    ON companies (normalized_name);

CREATE INDEX idx_companies_domain
    ON companies (canonical_domain);


-- Create Career Sites table

CREATE TABLE career_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    company_id BIGINT NOT NULL,

    site_name VARCHAR(200),

    career_url VARCHAR(2048) NOT NULL,

    ats_provider VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN',

    detection_status VARCHAR(40) NOT NULL DEFAULT 'UNCHECKED',

    tenant VARCHAR(255),

    cluster VARCHAR(50),

    site_slug VARCHAR(255),

    locale VARCHAR(20),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    last_checked_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_career_sites_company
        FOREIGN KEY (company_id)
        REFERENCES companies(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_career_sites_url
        UNIQUE (career_url),

    CONSTRAINT chk_career_sites_ats_provider
        CHECK (
            ats_provider IN (
                'WORKDAY',
                'GREENHOUSE',
                'LEVER',
                'ASHBY',
                'SMARTRECRUITERS',
                'WORKABLE',
                'RECRUITEE',
                'PERSONIO',
                'TEAMTAILOR',
                'RIPPLING',
                'BREEZY_HR',
                'CUSTOM',
                'UNKNOWN'
            )
        ),

    CONSTRAINT chk_career_sites_detection_status
        CHECK (
            detection_status IN (
                'UNCHECKED',
                'DETECTED',
                'VERIFIED',
                'UNSUPPORTED',
                'TEMPORARILY_UNAVAILABLE',
                'FAILED'
            )
        )
);

-- Career Site indexes

CREATE INDEX idx_career_sites_company_id
    ON career_sites (company_id);

CREATE INDEX idx_career_sites_ats_provider
    ON career_sites (ats_provider);

CREATE INDEX idx_career_sites_detection_status
    ON career_sites (detection_status);